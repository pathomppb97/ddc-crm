--
-- Document references (drawings, 8D/NCR/CAPA references, specifications...)
-- The CRM stores references and optional copies; it is not a document control system.
--

create or replace function public.ddc_entity_resource(p_entity_type text) returns text
    language sql immutable
    set search_path to ''
    as $$
        select case p_entity_type
            when 'companies' then 'customers'
            when 'leads' then 'leads'
            when 'deals' then 'opportunities'
            when 'activities' then 'activities'
            when 'products' then 'products'
            when 'rfqs' then 'rfqs'
            when 'quotations' then 'quotations'
            when 'dev_projects' then 'dev_projects'
            when 'service_cases' then 'service_cases'
        end
    $$;

create table public.document_references (
    id bigint generated by default as identity primary key,
    entity_type text not null check (public.ddc_entity_resource(entity_type) is not null),
    entity_id bigint not null,
    document_type_id bigint references public.master_options(id),
    title text not null,
    reference_no text,
    revision text,
    external_url text,
    file jsonb,
    notes text,
    sales_id bigint references public.sales(id),
    created_at timestamp with time zone not null default now()
);

create index document_references_entity_idx on public.document_references using btree (entity_type, entity_id);

create trigger document_references_check_options
    before insert or update on public.document_references
    for each row execute function public.ddc_check_option_category('document_type_id', 'document_type');
