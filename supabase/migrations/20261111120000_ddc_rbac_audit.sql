create or replace function public.current_sales_id() returns bigint
    language sql stable security definer
    set search_path to ''
    as $$
        select s.id from public.sales s where s.user_id = auth.uid() and not s.disabled
    $$;

create or replace function public.current_role_key() returns text
    language sql stable security definer
    set search_path to ''
    as $$
        select s.role_key from public.sales s where s.user_id = auth.uid() and not s.disabled
    $$;

-- The single authorization predicate used by every RLS policy and workflow function.
create or replace function public.ddc_can(p_resource text, p_action text, p_owner bigint default null) returns boolean
    language sql stable security definer
    set search_path to ''
    as $$
        select coalesce((
            select s.administrator or exists (
                select 1
                from public.role_permissions rp
                where rp.role_key = s.role_key
                    and rp.resource = p_resource
                    and rp.action = p_action
                    and (rp.scope = 'all' or (rp.scope = 'own' and p_owner is not null and p_owner = s.id))
            )
            from public.sales s
            where s.user_id = auth.uid() and not s.disabled
        ), false)
    $$;

-- True when the user holds the permission in any scope (used for child rows and list screens).
create or replace function public.ddc_can_any_scope(p_resource text, p_action text) returns boolean
    language sql stable security definer
    set search_path to ''
    as $$
        select coalesce((
            select s.administrator or exists (
                select 1
                from public.role_permissions rp
                where rp.role_key = s.role_key
                    and rp.resource = p_resource
                    and rp.action = p_action
            )
            from public.sales s
            where s.user_id = auth.uid() and not s.disabled
        ), false)
    $$;

-- Effective permissions of the connected user, consumed by the web application.
create or replace function public.ddc_my_permissions() returns table(resource text, action text, scope text)
    language sql stable security definer
    set search_path to ''
    as $$
        select rp.resource, rp.action, rp.scope
        from public.role_permissions rp
        join public.sales s on s.role_key = rp.role_key
        where s.user_id = auth.uid() and not s.disabled
    $$;

