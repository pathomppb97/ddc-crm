create index master_options_category_idx on public.master_options using btree (category, sort_order);

-- Guards option foreign keys: TG_ARGV is a list of (column, category) pairs.
create or replace function public.ddc_check_option_category() returns trigger
    language plpgsql
    set search_path to ''
    as $$
declare
    i integer := 0;
    v_value bigint;
    v_category text;
begin
    while i < tg_nargs loop
        v_value := (to_jsonb(new) ->> tg_argv[i])::bigint;
        if v_value is not null then
            select mo.category into v_category from public.master_options mo where mo.id = v_value;
            if v_category is distinct from tg_argv[i + 1] then
                raise exception 'Option % is not valid for %.% (expected category %)', v_value, tg_table_name, tg_argv[i], tg_argv[i + 1]
                    using errcode = '23514';
            end if;
        end if;
        i := i + 2;
    end loop;
    return new;
end;
$$;

-- Assigns a document number when none is given. TG_ARGV: column, prefix, sequence name.
create or replace function public.ddc_assign_doc_no() returns trigger
    language plpgsql
    set search_path to ''
    as $$
declare
    v_current text := to_jsonb(new) ->> tg_argv[0];
    v_no text;
begin
    if v_current is null or btrim(v_current) = '' then
        v_no := tg_argv[1] || '-' || to_char(now(), 'YYYY') || '-' || lpad(nextval(('public.' || tg_argv[2])::regclass)::text, 5, '0');
        new := jsonb_populate_record(new, jsonb_build_object(tg_argv[0], v_no));
    end if;
    return new;
end;
$$;

