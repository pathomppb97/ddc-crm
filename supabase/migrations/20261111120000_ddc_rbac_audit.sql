create table public.audit_log (
    id bigint generated by default as identity primary key,
    occurred_at timestamp with time zone not null default now(),
    actor_user_id uuid,
    actor_sales_id bigint,
    table_name text not null,
    record_id text,
    action text not null check (action in ('INSERT', 'UPDATE', 'DELETE')),
    changed_fields text[],
    old_data jsonb,
    new_data jsonb
);

create index audit_log_record_idx on public.audit_log using btree (table_name, record_id);
create index audit_log_occurred_at_idx on public.audit_log using btree (occurred_at desc);
create index audit_log_actor_idx on public.audit_log using btree (actor_sales_id);

create or replace function public.ddc_audit() returns trigger
    language plpgsql security definer
    set search_path to ''
    as $$
declare
    v_old jsonb;
    v_new jsonb;
    v_changed text[];
begin
    if tg_op <> 'INSERT' then
        v_old := to_jsonb(old) - 'fts';
    end if;
    if tg_op <> 'DELETE' then
        v_new := to_jsonb(new) - 'fts';
    end if;
    if tg_op = 'UPDATE' then
        -- Kanban reordering (index) and housekeeping timestamps are not business changes
        select array_agg(n.key order by n.key) into v_changed
        from jsonb_each(v_new) n
        where n.value is distinct from (v_old -> n.key)
            and n.key not in ('updated_at', 'index');
        if v_changed is null then
            return null;
        end if;
    end if;
    insert into public.audit_log (actor_user_id, actor_sales_id, table_name, record_id, action, changed_fields, old_data, new_data)
    values (
        auth.uid(),
        (select s.id from public.sales s where s.user_id = auth.uid()),
        tg_table_name,
        coalesce(v_new ->> 'id', v_old ->> 'id', v_new ->> 'key', v_old ->> 'key'),
        tg_op,
        v_changed,
        v_old,
        v_new
    );
    return null;
end;
$$;

create or replace function public.ddc_touch_updated_at() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

