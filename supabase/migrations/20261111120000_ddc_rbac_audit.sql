--
-- DDC CRM - 1/8 - Role based access control, audit log, configurable master data
--
-- Access rights are data, not code: roles and their permissions live in
-- ddc_roles / role_permissions and are edited from the administration UI.
-- Every business table gets its RLS policies from table_permission_map
-- (see 20261111120600_ddc_policies_grants.sql), so the same matrix is enforced
-- by PostgreSQL for every client, not only by the web application.
--

create table public.ddc_roles (
    key text primary key check (key ~ '^[a-z][a-z0-9_]*$'),
    name text not null,
    name_en text,
    description text,
    is_system boolean not null default false,
    sort_order integer not null default 0,
    created_at timestamp with time zone not null default now()
);

create table public.permission_resources (
    key text primary key check (key ~ '^[a-z][a-z0-9_]*$'),
    name text not null,
    name_en text,
    sort_order integer not null default 0
);

create table public.role_permissions (
    id bigint generated by default as identity primary key,
    role_key text not null references public.ddc_roles(key) on update cascade on delete cascade,
    resource text not null references public.permission_resources(key) on update cascade on delete cascade,
    action text not null check (action in ('read', 'create', 'update', 'delete', 'approve', 'export', 'import')),
    -- 'own' restricts the action to records owned by the user (owner column of the table)
    scope text not null default 'all' check (scope in ('all', 'own')),
    constraint role_permissions_unique unique (role_key, resource, action)
);

create index role_permissions_role_key_idx on public.role_permissions using btree (role_key);

alter table public.sales
    add column role_key text references public.ddc_roles(key) on update cascade on delete set null;

create index sales_role_key_idx on public.sales using btree (role_key);

-- Maps a table to the permission resource that protects it.
-- owner_column: column holding the owning sales.id (enables the 'own' scope).
-- parent_table/parent_fk: child rows inherit visibility and ownership from their parent row.
create table public.table_permission_map (
    table_name text primary key,
    resource text not null references public.permission_resources(key) on update cascade,
    owner_column text,
    parent_table text,
    parent_fk text,
    parent_owner_column text,
    constraint table_permission_map_parent_complete check (
        (parent_table is null and parent_fk is null and parent_owner_column is null)
        or (parent_table is not null and parent_fk is not null)
    )
);

