-- 6. Policy Version Invalidation Helper RPC
-- ============================================================================

create or replace function public.ddc_bump_policy_version(p_org_id bigint default 1) returns bigint
    language plpgsql security definer
    set search_path to ''
    as $$
declare
    v_ver bigint;
begin
    if not (public.is_admin() or public.ddc_can('mcp_admin', 'update') or public.ddc_can('roles', 'update')) then
        raise exception 'Not allowed to update authorization policies' using errcode = '42501';
    end if;

    update public.organizations
    set policy_version = policy_version + 1,
        updated_at = now()
    where id = p_org_id
    returning policy_version into v_ver;

    return v_ver;
end;
$$;

