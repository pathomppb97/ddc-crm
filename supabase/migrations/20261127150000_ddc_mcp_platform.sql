-- Audit triggers on governance tables (execution_logs & security_events are append-only log tables themselves)
do $$
declare
    t text;
begin
    foreach t in array array[
        'organizations', 'mcp_tools', 'mcp_role_policies', 'mcp_tool_permissions',
        'mcp_user_policies', 'mcp_clients', 'oauth_grants', 'mcp_connections',
        'mcp_approval_requests', 'saved_reports'
    ] loop
        execute format('create trigger zz_audit after insert or update or delete on public.%I for each row execute function public.ddc_audit()', t);
    end loop;

    foreach t in array array[
        'organizations', 'mcp_tools', 'mcp_role_policies', 'mcp_tool_permissions',
        'mcp_user_policies', 'mcp_clients', 'mcp_approval_requests'
    ] loop
        execute format('create trigger aa_touch_updated_at before update on public.%I for each row execute function public.ddc_touch_updated_at()', t);
    end loop;

    foreach t in array array[
        'organizations', 'mcp_tools', 'mcp_role_policies', 'mcp_tool_permissions',
        'mcp_user_policies', 'mcp_clients', 'oauth_grants', 'mcp_connections',
        'mcp_approval_requests', 'mcp_execution_logs', 'mcp_security_events', 'saved_reports'
    ] loop
        execute format('revoke all on table public.%I from anon', t);
        execute format('grant all on table public.%I to service_role', t);
        if t in ('mcp_execution_logs', 'mcp_security_events') then
            -- Append-only: authenticated users can only SELECT (service_role writes)
            execute format('revoke all on table public.%I from authenticated', t);
            execute format('grant select on table public.%I to authenticated', t);
        else
            execute format('grant select, insert, update, delete on table public.%I to authenticated', t);
        end if;
    end loop;

    foreach t in array array[
        'organizations_id_seq', 'mcp_role_policies_id_seq', 'mcp_tool_permissions_id_seq',
        'mcp_user_policies_id_seq', 'mcp_clients_id_seq', 'oauth_grants_id_seq',
        'mcp_connections_id_seq', 'mcp_approval_requests_id_seq',
        'mcp_execution_logs_id_seq', 'mcp_security_events_id_seq', 'saved_reports_id_seq'
    ] loop
        execute format('revoke all on sequence public.%I from anon', t);
        execute format('grant usage, select on sequence public.%I to authenticated', t);
        execute format('grant all on sequence public.%I to service_role', t);
    end loop;
end;
$$;

