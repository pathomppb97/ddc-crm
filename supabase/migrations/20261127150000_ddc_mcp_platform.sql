create or replace function public.ddc_audit() returns trigger
    language plpgsql security definer
    set search_path to ''
    as $$
declare
    v_old jsonb;
    v_new jsonb;
    v_changed text[];
    v_channel text;
    v_approval_text text;
    v_approval_id bigint;
    v_actor_sales_id bigint;
    v_actor_org_id bigint;
begin
    if tg_op <> 'INSERT' then
        v_old := public.ddc_sanitize_audit_jsonb(to_jsonb(old) - 'fts');
    end if;
    if tg_op <> 'DELETE' then
        v_new := public.ddc_sanitize_audit_jsonb(to_jsonb(new) - 'fts');
    end if;
    if tg_op = 'UPDATE' then
        select array_agg(n.key order by n.key) into v_changed
        from jsonb_each(v_new) n
        where n.value is distinct from (v_old -> n.key)
          and n.key not in ('updated_at', 'index', 'version');
        if v_changed is null then
            return null;
        end if;
    end if;

    v_channel := nullif(current_setting('app.channel', true), '');
    if v_channel is null or v_channel not in ('web', 'rest_api', 'mcp', 'integration_api', 'worker', 'system') then
        v_channel := 'web';
    end if;

    v_approval_text := nullif(current_setting('app.approval_request_id', true), '');
    if v_approval_text ~ '^\d+$' then
        v_approval_id := v_approval_text::bigint;
    end if;

    select s.id, s.organization_id
    into v_actor_sales_id, v_actor_org_id
    from public.sales s
    where s.user_id = auth.uid();

    insert into public.audit_log (
        actor_user_id,
        actor_sales_id,
        organization_id,
        table_name,
        record_id,
        action,
        changed_fields,
        old_data,
        new_data,
        request_id,
        actor_ip,
        actor_user_agent,
        reason,
        channel,
        ai_client_id,
        mcp_tool_name,
        approval_request_id
    )
    values (
        auth.uid(),
        v_actor_sales_id,
        coalesce(v_actor_org_id, 1),
        tg_table_name,
        coalesce(
            v_new ->> 'id', v_old ->> 'id',
            v_new ->> 'tool_id', v_old ->> 'tool_id',
            v_new ->> 'key', v_old ->> 'key',
            v_new ->> 'flag_key', v_old ->> 'flag_key'
        ),
        tg_op,
        v_changed,
        v_old,
        v_new,
        nullif(current_setting('app.request_id', true), ''),
        nullif(current_setting('app.actor_ip', true), ''),
        nullif(current_setting('app.actor_user_agent', true), ''),
        nullif(current_setting('app.audit_reason', true), ''),
        v_channel,
        nullif(current_setting('app.ai_client_id', true), ''),
        nullif(current_setting('app.mcp_tool_name', true), ''),
        v_approval_id
    );
    return null;
end;
$$;

