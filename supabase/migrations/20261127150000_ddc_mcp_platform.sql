create or replace function public.current_organization_id() returns bigint
    language sql stable security definer
    set search_path to ''
    as $$
        select s.organization_id
        from public.sales s
        where s.user_id = auth.uid()
          and not s.disabled
    $$;

create or replace function public.same_organization(p_org_id bigint) returns boolean
    language sql stable security definer
    set search_path to ''
    as $$
        select exists (
            select 1
            from public.sales s
            join public.organizations o on o.id = s.organization_id
            where s.user_id = auth.uid()
              and not s.disabled
              and o.is_active
              and s.organization_id = p_org_id
        )
    $$;

-- Tighten companies RLS with organization isolation while preserving existing RBAC semantics
drop policy if exists ddc_select on public.companies;
drop policy if exists ddc_insert on public.companies;
drop policy if exists ddc_update on public.companies;
drop policy if exists ddc_delete on public.companies;

create policy ddc_select on public.companies for select to authenticated
    using (public.same_organization(organization_id) and public.ddc_can('customers', 'read', sales_id));
create policy ddc_insert on public.companies for insert to authenticated
    with check (public.same_organization(organization_id) and public.ddc_can('customers', 'create', sales_id));
create policy ddc_update on public.companies for update to authenticated
    using (public.same_organization(organization_id) and public.ddc_can('customers', 'update', sales_id))
    with check (public.same_organization(organization_id) and public.ddc_can('customers', 'update', sales_id));
create policy ddc_delete on public.companies for delete to authenticated
    using (public.same_organization(organization_id) and public.ddc_can('customers', 'delete', sales_id));

