--
-- DDC CRM - 3/8 - Product master, automotive fitment, agricultural machinery applications
--
-- CRM product ids are independent from ERP item numbers: the link to the ERP item
-- master lives in erp_external_ids (see 20261111120500_ddc_erp.sql).
-- Fitment and application rows carry a verification status: nothing is assumed
-- compatible until a person records the evidence source.
