create table public.company_product_interests (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    division_id bigint references public.divisions(id),
    node_id bigint references public.product_hierarchy_nodes(id) on delete cascade,
    product_id bigint references public.products(id) on delete cascade,
    interest_level text check (interest_level in ('low', 'medium', 'high')),
    notes text,
    created_at timestamp with time zone not null default now(),
    constraint company_product_interests_has_target check (num_nonnulls(division_id, node_id, product_id) >= 1)
);

create index company_product_interests_company_idx on public.company_product_interests using btree (company_id);
create index company_product_interests_product_idx on public.company_product_interests using btree (product_id);
create index company_product_interests_node_idx on public.company_product_interests using btree (node_id);

