-- Hierarchy below the division: family > category > type > model. Levels may be skipped.
create table public.product_hierarchy_nodes (
    id bigint generated by default as identity primary key,
    division_id bigint not null references public.divisions(id),
    parent_id bigint references public.product_hierarchy_nodes(id) on delete restrict,
    level text not null check (level in ('family', 'category', 'type', 'model')),
    code text not null,
    name text not null,
    name_en text,
    is_active boolean not null default true,
    sort_order integer not null default 0,
    constraint product_hierarchy_nodes_unique unique (division_id, level, code),
    constraint product_hierarchy_nodes_not_own_parent check (parent_id is null or parent_id <> id)
);

create index product_hierarchy_nodes_parent_id_idx on public.product_hierarchy_nodes using btree (parent_id);
create index product_hierarchy_nodes_division_idx on public.product_hierarchy_nodes using btree (division_id, level);

create or replace function public.ddc_hierarchy_level_rank(p_level text) returns integer
    language sql immutable
    set search_path to ''
    as $$
        select case p_level when 'family' then 1 when 'category' then 2 when 'type' then 3 when 'model' then 4 end
    $$;

create or replace function public.ddc_check_hierarchy_node() returns trigger
    language plpgsql
    set search_path to ''
    as $$
declare
    v_parent public.product_hierarchy_nodes%rowtype;
begin
    if new.parent_id is null then
        return new;
    end if;
    select * into v_parent from public.product_hierarchy_nodes where id = new.parent_id;
    if v_parent.division_id <> new.division_id then
        raise exception 'A hierarchy node must belong to the same division as its parent' using errcode = '23514';
    end if;
    if public.ddc_hierarchy_level_rank(v_parent.level) >= public.ddc_hierarchy_level_rank(new.level) then
        raise exception 'A % node cannot be placed under a % node', new.level, v_parent.level using errcode = '23514';
    end if;
    return new;
end;
$$;

create trigger product_hierarchy_nodes_check
    before insert or update on public.product_hierarchy_nodes
    for each row execute function public.ddc_check_hierarchy_node();

create table public.manufacturers (
    id bigint generated by default as identity primary key,
    name text not null unique,
    kind text not null default 'vehicle' check (kind in ('vehicle', 'machinery', 'both')),
    country text,
    is_active boolean not null default true
);

create table public.brands (
    id bigint generated by default as identity primary key,
    code text not null unique,
    name text not null,
    owner_type text not null default 'ddc_owned' check (owner_type in ('ddc_owned', 'customer', 'third_party')),
    division_id bigint references public.divisions(id),
    description text,
    is_active boolean not null default true
);

create table public.products (
    id bigint generated by default as identity primary key,
    part_number text not null unique,
    name text not null,
    name_en text,
    -- null: imported from the ERP and not classified yet
    division_id bigint references public.divisions(id),
    node_id bigint references public.product_hierarchy_nodes(id) on delete set null,
    brand_id bigint references public.brands(id) on delete set null,
    lifecycle_status_id bigint references public.master_options(id),
    material text,
    uom text,
    description text,
    current_revision text,
    custom_fields jsonb not null default '{}'::jsonb,
    sales_id bigint references public.sales(id),
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    fts tsvector generated always as (
        setweight(public.search_document(part_number, name, name_en), 'A')
        || public.search_document(material, description)
    ) stored
);

create index products_division_id_idx on public.products using btree (division_id);
create index products_node_id_idx on public.products using btree (node_id);
create index products_brand_id_idx on public.products using btree (brand_id);
create index products_lifecycle_status_id_idx on public.products using btree (lifecycle_status_id);
create index products_fts_idx on public.products using gin (fts);

create trigger products_check_options
    before insert or update on public.products
    for each row execute function public.ddc_check_option_category('lifecycle_status_id', 'product_lifecycle_status');

create or replace function public.ddc_check_product_node() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
    if new.node_id is not null and not exists (
        select 1 from public.product_hierarchy_nodes n where n.id = new.node_id and n.division_id = new.division_id
    ) then
        raise exception 'The product hierarchy node must belong to the product division' using errcode = '23514';
    end if;
    return new;
end;
$$;

create trigger products_check_node
    before insert or update on public.products
    for each row execute function public.ddc_check_product_node();

