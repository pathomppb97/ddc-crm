create or replace function public.ddc_stamp_verification() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
    if new.verification_status = 'verified'
        and (tg_op = 'INSERT' or old.verification_status is distinct from 'verified') then
        new.verified_by := public.current_sales_id();
        new.verified_at := now();
    elsif new.verification_status = 'unverified' then
        new.verified_by := null;
        new.verified_at := null;
    end if;
    return new;
end;
$$;

create trigger product_vehicle_fitments_stamp
    before insert or update on public.product_vehicle_fitments
    for each row execute function public.ddc_stamp_verification();

