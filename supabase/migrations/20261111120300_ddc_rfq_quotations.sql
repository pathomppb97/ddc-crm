--
-- Workflow functions (security definer: they perform their own permission checks)
--

create or replace function public.submit_quotation(p_quotation_id bigint) returns public.quotations
    language plpgsql security definer
    set search_path to ''
    as $$
declare
    v_q public.quotations%rowtype;
    v_rules integer;
begin
    select * into v_q from public.quotations where id = p_quotation_id for update;
    if not found then
        raise exception 'Quotation % not found', p_quotation_id using errcode = 'P0002';
    end if;
    if not public.ddc_can('quotations', 'update', v_q.sales_id) then
        raise exception 'Not allowed to submit this quotation' using errcode = '42501';
    end if;
    if v_q.status not in ('draft', 'rejected') then
        raise exception 'Only a draft or rejected quotation can be submitted (current status: %)', v_q.status using errcode = '22023';
    end if;
    if not exists (select 1 from public.quotation_items i where i.quotation_id = p_quotation_id) then
        raise exception 'A quotation needs at least one line before submission' using errcode = '22023';
    end if;

    perform set_config('ddc.workflow', '1', true);

    update public.quotation_approvals set status = 'cancelled'
    where quotation_id = p_quotation_id and status = 'pending';

    insert into public.quotation_approvals (quotation_id, rule_id, required_role_key)
    select p_quotation_id, r.id, r.approver_role_key
    from public.approval_rules r
    where r.is_active
        and (r.division_id is null or r.division_id = v_q.division_id)
        and (r.currency is null or r.currency = v_q.currency)
        and v_q.total_amount >= r.min_amount
        and (r.max_amount is null or v_q.total_amount <= r.max_amount)
    order by r.sort_order, r.id;
    get diagnostics v_rules = row_count;

    -- No rule matched: the quotation still needs one decision from a user holding the approve permission
    if v_rules = 0 then
        insert into public.quotation_approvals (quotation_id, rule_id, required_role_key)
        values (p_quotation_id, null, null);
    end if;

    update public.quotations
    set status = 'pending_approval', submitted_at = now(), submitted_by = public.current_sales_id(), approved_at = null
    where id = p_quotation_id
    returning * into v_q;

    perform public.ddc_notify(s.id, 'quotation.approval_requested', 'Quotation approval requested',
        v_q.quotation_no || ' rev. ' || v_q.revision, 'quotations', v_q.id)
    from public.sales s
    where not s.disabled
        and s.id is distinct from v_q.submitted_by
        and exists (
            select 1 from public.quotation_approvals a
            where a.quotation_id = p_quotation_id and a.status = 'pending'
                and (a.required_role_key = s.role_key
                    or (a.required_role_key is null and exists (
                        select 1 from public.role_permissions rp
                        where rp.role_key = s.role_key and rp.resource = 'quotations' and rp.action = 'approve')))
        );

    perform set_config('ddc.workflow', '', true);
    return v_q;
end;
$$;

create or replace function public.decide_quotation_approval(
    p_approval_id bigint, p_decision text, p_comment text default null
) returns public.quotations
    language plpgsql security definer
    set search_path to ''
    as $$
declare
    v_a public.quotation_approvals%rowtype;
    v_q public.quotations%rowtype;
    v_me public.sales%rowtype;
begin
    if p_decision not in ('approved', 'rejected') then
        raise exception 'Decision must be approved or rejected' using errcode = '22023';
    end if;
    select * into v_me from public.sales where user_id = auth.uid() and not disabled;
    if not found then
        raise exception 'Not authenticated' using errcode = '42501';
    end if;
    select * into v_a from public.quotation_approvals where id = p_approval_id for update;
    if not found then
        raise exception 'Approval % not found', p_approval_id using errcode = 'P0002';
    end if;
    select * into v_q from public.quotations where id = v_a.quotation_id for update;
    if v_a.status <> 'pending' or v_q.status <> 'pending_approval' then
        raise exception 'This approval is no longer pending' using errcode = '22023';
    end if;
    if not public.ddc_can('quotations', 'approve') then
        raise exception 'Not allowed to approve quotations' using errcode = '42501';
    end if;
    if v_a.required_role_key is not null and not v_me.administrator
        and v_me.role_key is distinct from v_a.required_role_key then
        raise exception 'This approval requires the role %', v_a.required_role_key using errcode = '42501';
    end if;
    if v_q.submitted_by = v_me.id and not public.ddc_setting_bool('quotation_allow_self_approval', false) then
        raise exception 'The submitter cannot approve their own quotation' using errcode = '42501';
    end if;
    if p_decision = 'rejected' and (p_comment is null or btrim(p_comment) = '') then
        raise exception 'A comment is required to reject a quotation' using errcode = '22023';
    end if;

    perform set_config('ddc.workflow', '1', true);

    update public.quotation_approvals
    set status = p_decision, decided_by = v_me.id, decided_at = now(), comment = p_comment
    where id = p_approval_id;

    if p_decision = 'rejected' then
        update public.quotation_approvals set status = 'cancelled'
        where quotation_id = v_q.id and status = 'pending';
        update public.quotations set status = 'rejected' where id = v_q.id returning * into v_q;
    elsif not exists (
        select 1 from public.quotation_approvals where quotation_id = v_q.id and status = 'pending'
    ) then
        update public.quotations set status = 'approved', approved_at = now() where id = v_q.id returning * into v_q;
    end if;

    if v_q.status in ('approved', 'rejected') then
        perform public.ddc_notify(v_q.sales_id, 'quotation.' || v_q.status, 'Quotation ' || v_q.status,
            v_q.quotation_no || ' rev. ' || v_q.revision, 'quotations', v_q.id);
    end if;

    perform set_config('ddc.workflow', '', true);
    return v_q;
end;
$$;

create or replace function public.set_quotation_status(p_quotation_id bigint, p_status text) returns public.quotations
    language plpgsql security definer
    set search_path to ''
    as $$
declare
    v_q public.quotations%rowtype;
    v_allowed boolean;
begin
    select * into v_q from public.quotations where id = p_quotation_id for update;
    if not found then
        raise exception 'Quotation % not found', p_quotation_id using errcode = 'P0002';
    end if;
    if not public.ddc_can('quotations', 'update', v_q.sales_id) then
        raise exception 'Not allowed to update this quotation' using errcode = '42501';
    end if;
    v_allowed := case
        when v_q.status in ('draft', 'rejected') and p_status = 'cancelled' then true
        when v_q.status = 'approved' and p_status in ('sent', 'cancelled') then true
        when v_q.status = 'sent' and p_status in ('accepted', 'declined', 'expired') then true
        else false
    end;
    if not v_allowed then
        raise exception 'Transition from % to % is not allowed', v_q.status, p_status using errcode = '22023';
    end if;

    perform set_config('ddc.workflow', '1', true);
    update public.quotations
    set status = p_status,
        sent_at = case when p_status = 'sent' then now() else sent_at end,
        decided_at = case when p_status in ('accepted', 'declined', 'expired') then now() else decided_at end
    where id = p_quotation_id
    returning * into v_q;
    if p_status = 'sent' and v_q.rfq_id is not null then
        update public.rfqs set status = 'quoted' where id = v_q.rfq_id and status not in ('closed', 'cancelled');
    end if;
    perform set_config('ddc.workflow', '', true);
    return v_q;
end;
$$;

create or replace function public.create_quotation_revision(p_quotation_id bigint) returns public.quotations
    language plpgsql security definer
    set search_path to ''
    as $$
declare
    v_q public.quotations%rowtype;
    v_new public.quotations%rowtype;
begin
    select * into v_q from public.quotations where id = p_quotation_id for update;
    if not found then
        raise exception 'Quotation % not found', p_quotation_id using errcode = 'P0002';
    end if;
    if not public.ddc_can('quotations', 'create') or not public.ddc_can('quotations', 'update', v_q.sales_id) then
        raise exception 'Not allowed to revise this quotation' using errcode = '42501';
    end if;
    if v_q.status not in ('approved', 'sent', 'rejected', 'declined', 'expired') then
        raise exception 'A quotation in status % cannot be revised', v_q.status using errcode = '22023';
    end if;
    if exists (select 1 from public.quotations where quotation_no = v_q.quotation_no and revision > v_q.revision) then
        raise exception 'A newer revision of % already exists', v_q.quotation_no using errcode = '22023';
    end if;

    perform set_config('ddc.workflow', '1', true);

    insert into public.quotations (
        quotation_no, revision, previous_revision_id, rfq_id, deal_id, company_id, contact_id, division_id,
        subject, currency, status, valid_until, payment_terms, delivery_terms, notes, follow_up_date, sales_id
    )
    values (
        v_q.quotation_no, v_q.revision + 1, v_q.id, v_q.rfq_id, v_q.deal_id, v_q.company_id, v_q.contact_id, v_q.division_id,
        v_q.subject, v_q.currency, 'draft', v_q.valid_until, v_q.payment_terms, v_q.delivery_terms, v_q.notes, v_q.follow_up_date, v_q.sales_id
    )
    returning * into v_new;

    insert into public.quotation_items (quotation_id, line_no, product_id, rfq_item_id, description, quantity, uom, unit_price, discount_percent, lead_time_days, notes)
    select v_new.id, i.line_no, i.product_id, i.rfq_item_id, i.description, i.quantity, i.uom, i.unit_price, i.discount_percent, i.lead_time_days, i.notes
    from public.quotation_items i
    where i.quotation_id = v_q.id;

    update public.quotation_approvals set status = 'cancelled' where quotation_id = v_q.id and status = 'pending';
    update public.quotations set status = 'superseded' where id = v_q.id;

    perform set_config('ddc.workflow', '', true);
    select * into v_new from public.quotations where id = v_new.id;
    return v_new;
end;
$$;

-- Engineering review stamp on RFQs
create or replace function public.ddc_rfq_review_stamp() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
    if new.engineering_review_status in ('feasible', 'feasible_with_conditions', 'not_feasible')
        and (tg_op = 'INSERT' or new.engineering_review_status is distinct from old.engineering_review_status) then
        new.engineering_reviewer_id := coalesce(public.current_sales_id(), new.engineering_reviewer_id);
        new.engineering_reviewed_at := now();
    end if;
    return new;
end;
$$;

create trigger rfqs_review_stamp
    before insert or update on public.rfqs
    for each row execute function public.ddc_rfq_review_stamp();
