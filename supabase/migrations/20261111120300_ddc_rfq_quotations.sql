--
-- DDC CRM - 4/8 - RFQ, quotations, commercial approval workflow
--
-- RFQ, quotation and opportunity are three distinct entities with traceable links:
--   opportunity (deals) 1--n rfqs 1--n quotations (each quotation number has n revisions).
-- Quotation status only changes through the workflow functions below, which
-- enforce permissions, approval rules and locking in the database.
--

create sequence public.rfq_no_seq;
create sequence public.quotation_no_seq;

create table public.rfqs (
    id bigint generated by default as identity primary key,
    rfq_no text unique,
    customer_rfq_ref text,
    company_id bigint not null references public.companies(id) on delete restrict,
    contact_id bigint references public.contacts(id) on delete set null,
    deal_id bigint references public.deals(id) on delete set null,
    division_id bigint references public.divisions(id),
    subject text not null,
    received_date date not null default current_date,
    quotation_due_date date,
    requested_delivery_date date,
    customer_requirements text,
    status text not null default 'registered'
        check (status in ('registered', 'engineering_review', 'costing', 'quoted', 'closed', 'cancelled')),
    engineering_review_status text not null default 'not_required'
        check (engineering_review_status in ('not_required', 'pending', 'feasible', 'feasible_with_conditions', 'not_feasible')),
    engineering_notes text,
    engineering_reviewer_id bigint references public.sales(id),
    engineering_reviewed_at timestamp with time zone,
    cost_estimate_ref text,
    follow_up_date date,
    sales_id bigint references public.sales(id),
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);

create index rfqs_company_id_idx on public.rfqs using btree (company_id);
create index rfqs_deal_id_idx on public.rfqs using btree (deal_id);
create index rfqs_status_idx on public.rfqs using btree (status);
create index rfqs_sales_id_idx on public.rfqs using btree (sales_id);

