create table public.quotation_items (
    id bigint generated by default as identity primary key,
    quotation_id bigint not null references public.quotations(id) on delete cascade,
    line_no integer not null,
    product_id bigint references public.products(id) on delete restrict,
    rfq_item_id bigint references public.rfq_items(id) on delete set null,
    description text,
    quantity numeric(18, 3) not null check (quantity > 0),
    uom text,
    unit_price numeric(18, 4) not null check (unit_price >= 0),
    discount_percent numeric(5, 2) not null default 0 check (discount_percent between 0 and 100),
    line_total numeric(18, 4) generated always as (round(quantity * unit_price * (1 - discount_percent / 100), 4)) stored,
    lead_time_days integer check (lead_time_days is null or lead_time_days >= 0),
    notes text,
    constraint quotation_items_line_unique unique (quotation_id, line_no),
    constraint quotation_items_identified check (num_nonnulls(product_id, description) >= 1)
);

create index quotation_items_product_idx on public.quotation_items using btree (product_id);

-- Commercial approval rules, maintained by administrators.
create table public.approval_rules (
    id bigint generated by default as identity primary key,
    name text not null,
    division_id bigint references public.divisions(id),
    currency text check (currency is null or currency ~ '^[A-Z]{3}$'),
    min_amount numeric(18, 4) not null default 0 check (min_amount >= 0),
    max_amount numeric(18, 4),
    approver_role_key text not null references public.ddc_roles(key) on update cascade,
    is_active boolean not null default true,
    sort_order integer not null default 0,
    constraint approval_rules_range check (max_amount is null or max_amount >= min_amount)
);

create table public.quotation_approvals (
    id bigint generated by default as identity primary key,
    quotation_id bigint not null references public.quotations(id) on delete cascade,
    rule_id bigint references public.approval_rules(id) on delete set null,
    -- null: any user holding the quotations/approve permission may decide
    required_role_key text references public.ddc_roles(key) on update cascade,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'cancelled')),
    decided_by bigint references public.sales(id),
    decided_at timestamp with time zone,
    comment text,
    created_at timestamp with time zone not null default now()
);

create index quotation_approvals_quotation_idx on public.quotation_approvals using btree (quotation_id);
create index quotation_approvals_pending_idx on public.quotation_approvals using btree (required_role_key) where status = 'pending';

--
-- Guards: totals, locking and workflow-only status changes
--

create or replace function public.ddc_workflow_active() returns boolean
    language sql stable
    set search_path to ''
    as $$ select coalesce(current_setting('ddc.workflow', true), '') = '1' $$;

create or replace function public.ddc_quotation_guard() returns trigger
    language plpgsql
    set search_path to ''
    as $$
declare
    v_free text[] := array['follow_up_date', 'updated_at', 'total_amount'];
begin
    if public.ddc_workflow_active() then
        return new;
    end if;
    if tg_op = 'INSERT' then
        if new.status <> 'draft' then
            raise exception 'A quotation must be created as a draft' using errcode = '42501';
        end if;
        return new;
    end if;
    if new.status is distinct from old.status then
        raise exception 'The quotation status can only be changed through the approval workflow' using errcode = '42501';
    end if;
    if old.status not in ('draft', 'rejected')
        and (to_jsonb(new) - v_free) is distinct from (to_jsonb(old) - v_free) then
        raise exception 'Quotation % is locked in status %: create a revision to change it', old.quotation_no, old.status
            using errcode = '42501';
    end if;
    return new;
end;
$$;

create trigger quotations_guard
    before insert or update on public.quotations
    for each row execute function public.ddc_quotation_guard();

create or replace function public.ddc_quotation_items_guard() returns trigger
    language plpgsql
    set search_path to ''
    as $$
declare
    v_quotation_id bigint := coalesce(new.quotation_id, old.quotation_id);
    v_status text;
begin
    if not public.ddc_workflow_active() then
        select q.status into v_status from public.quotations q where q.id = v_quotation_id;
        -- v_status is null when the parent quotation is being deleted (cascade)
        if v_status is not null and v_status not in ('draft', 'rejected') then
            raise exception 'Quotation lines are locked in status %', v_status using errcode = '42501';
        end if;
    end if;
    return coalesce(new, old);
end;
$$;

create trigger quotation_items_guard
    before insert or update or delete on public.quotation_items
    for each row execute function public.ddc_quotation_items_guard();

create or replace function public.ddc_quotation_refresh_total() returns trigger
    language plpgsql security definer
    set search_path to ''
    as $$
declare
    v_quotation_id bigint := coalesce(new.quotation_id, old.quotation_id);
begin
    update public.quotations q
    set total_amount = coalesce((select sum(i.line_total) from public.quotation_items i where i.quotation_id = v_quotation_id), 0)
    where q.id = v_quotation_id;
    if tg_op = 'UPDATE' and old.quotation_id <> new.quotation_id then
        update public.quotations q
        set total_amount = coalesce((select sum(i.line_total) from public.quotation_items i where i.quotation_id = old.quotation_id), 0)
        where q.id = old.quotation_id;
    end if;
    return null;
end;
$$;

create trigger quotation_items_refresh_total
    after insert or update or delete on public.quotation_items
    for each row execute function public.ddc_quotation_refresh_total();

-- Approvals are written by the workflow functions only.
create or replace function public.ddc_workflow_only() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
    if not public.ddc_workflow_active() then
        raise exception '% rows can only be changed through the workflow functions', tg_table_name using errcode = '42501';
    end if;
    return coalesce(new, old);
end;
$$;

create trigger quotation_approvals_workflow_only
    before insert or update or delete on public.quotation_approvals
    for each row execute function public.ddc_workflow_only();

