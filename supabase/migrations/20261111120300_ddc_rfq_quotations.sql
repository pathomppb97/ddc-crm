create table public.rfq_items (
    id bigint generated by default as identity primary key,
    rfq_id bigint not null references public.rfqs(id) on delete cascade,
    line_no integer not null,
    product_id bigint references public.products(id) on delete restrict,
    customer_part_number text,
    description text,
    quantity numeric(18, 3) check (quantity is null or quantity > 0),
    uom text,
    target_price numeric(18, 4) check (target_price is null or target_price >= 0),
    currency text,
    requested_specification text,
    requested_delivery_date date,
    drawing_no text,
    drawing_revision text,
    constraint rfq_items_line_unique unique (rfq_id, line_no),
    constraint rfq_items_identified check (num_nonnulls(product_id, customer_part_number, description) >= 1)
);

create index rfq_items_product_idx on public.rfq_items using btree (product_id);

create table public.quotations (
    id bigint generated by default as identity primary key,
    quotation_no text,
    revision integer not null default 0 check (revision >= 0),
    previous_revision_id bigint references public.quotations(id) on delete set null,
    rfq_id bigint references public.rfqs(id) on delete set null,
    deal_id bigint references public.deals(id) on delete set null,
    company_id bigint not null references public.companies(id) on delete restrict,
    contact_id bigint references public.contacts(id) on delete set null,
    division_id bigint references public.divisions(id),
    subject text not null,
    currency text not null default 'THB' check (currency ~ '^[A-Z]{3}$'),
    status text not null default 'draft'
        check (status in ('draft', 'pending_approval', 'approved', 'rejected', 'sent', 'accepted', 'declined', 'expired', 'superseded', 'cancelled')),
    valid_until date,
    payment_terms text,
    delivery_terms text,
    notes text,
    -- Quoted value. Not a sales order and not revenue.
    total_amount numeric(18, 4) not null default 0,
    follow_up_date date,
    sales_id bigint references public.sales(id),
    submitted_by bigint references public.sales(id),
    submitted_at timestamp with time zone,
    approved_at timestamp with time zone,
    sent_at timestamp with time zone,
    decided_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint quotations_no_revision_unique unique (quotation_no, revision)
);

create index quotations_company_id_idx on public.quotations using btree (company_id);
create index quotations_rfq_id_idx on public.quotations using btree (rfq_id);
create index quotations_deal_id_idx on public.quotations using btree (deal_id);
create index quotations_status_idx on public.quotations using btree (status);
create index quotations_sales_id_idx on public.quotations using btree (sales_id);

