create table public.service_cases (
    id bigint generated by default as identity primary key,
    case_no text unique,
    company_id bigint not null references public.companies(id) on delete restrict,
    contact_id bigint references public.contacts(id) on delete set null,
    customer_reference text,
    category_id bigint references public.master_options(id),
    subject text not null,
    description text,
    priority text not null default 'medium' check (priority in ('low', 'medium', 'high', 'critical')),
    status text not null default 'open'
        check (status in ('open', 'investigating', 'corrective_action', 'awaiting_customer', 'closed', 'cancelled')),
    received_date date not null default current_date,
    due_date date,
    assigned_department_id bigint references public.master_options(id),
    sales_id bigint references public.sales(id),
    investigation_summary text,
    corrective_action_summary text,
    -- References to documents owned by the Quality Management System
    external_8d_ref text,
    external_ncr_ref text,
    external_capa_ref text,
    closure_summary text,
    closed_at timestamp with time zone,
    closed_by bigint references public.sales(id),
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint service_cases_closed_has_summary check (
        status <> 'closed' or (closure_summary is not null and btrim(closure_summary) <> '')
    )
);

create index service_cases_company_idx on public.service_cases using btree (company_id);
create index service_cases_status_idx on public.service_cases using btree (status, priority);
create index service_cases_sales_idx on public.service_cases using btree (sales_id);

create trigger service_cases_assign_no
    before insert on public.service_cases
    for each row execute function public.ddc_assign_doc_no('case_no', 'CASE', 'service_case_no_seq');

create trigger service_cases_set_sales_id
    before insert on public.service_cases
    for each row execute function public.set_sales_id_default();

create trigger service_cases_check_options
    before insert or update on public.service_cases
    for each row execute function public.ddc_check_option_category(
        'category_id', 'complaint_category',
        'assigned_department_id', 'department'
    );

create or replace function public.ddc_service_case_closure() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
    if new.status = 'closed' and (tg_op = 'INSERT' or old.status is distinct from 'closed') then
        new.closed_at := now();
        new.closed_by := public.current_sales_id();
    elsif new.status <> 'closed' then
        new.closed_at := null;
        new.closed_by := null;
    end if;
    return new;
end;
$$;

create trigger service_cases_closure
    before insert or update on public.service_cases
    for each row execute function public.ddc_service_case_closure();

create table public.service_case_products (
    id bigint generated by default as identity primary key,
    case_id bigint not null references public.service_cases(id) on delete cascade,
    product_id bigint references public.products(id) on delete restrict,
    description text,
    quantity numeric(18, 3) check (quantity is null or quantity >= 0),
    uom text,
    lot_reference text,
    constraint service_case_products_identified check (num_nonnulls(product_id, description) >= 1)
);

create index service_case_products_case_idx on public.service_case_products using btree (case_id);
create index service_case_products_product_idx on public.service_case_products using btree (product_id);

