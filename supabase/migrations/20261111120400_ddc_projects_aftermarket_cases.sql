create sequence public.dev_project_no_seq;
create sequence public.service_case_no_seq;

create table public.dev_projects (
    id bigint generated by default as identity primary key,
    project_no text unique,
    name text not null,
    company_id bigint not null references public.companies(id) on delete restrict,
    deal_id bigint references public.deals(id) on delete set null,
    rfq_id bigint references public.rfqs(id) on delete set null,
    business_model_id bigint references public.business_models(id),
    division_id bigint references public.divisions(id),
    product_id bigint references public.products(id) on delete set null,
    status text not null default 'inquiry'
        check (status in ('inquiry', 'requirements', 'feasibility', 'tooling', 'sampling', 'customer_approval', 'production_ready', 'on_hold', 'cancelled', 'completed')),
    inquiry_summary text,
    feasibility_status text not null default 'pending'
        check (feasibility_status in ('pending', 'feasible', 'feasible_with_conditions', 'not_feasible')),
    feasibility_notes text,
    process_considerations text,
    material_requirements text,
    tooling_requirements text,
    customer_approval_status text not null default 'not_submitted'
        check (customer_approval_status in ('not_submitted', 'submitted', 'approved', 'conditionally_approved', 'rejected')),
    estimated_production_ready_date date,
    responsible_department_id bigint references public.master_options(id),
    sales_id bigint references public.sales(id),
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);

create index dev_projects_company_id_idx on public.dev_projects using btree (company_id);
create index dev_projects_status_idx on public.dev_projects using btree (status);
create index dev_projects_sales_id_idx on public.dev_projects using btree (sales_id);

create trigger dev_projects_assign_no
    before insert on public.dev_projects
    for each row execute function public.ddc_assign_doc_no('project_no', 'DEV', 'dev_project_no_seq');

create trigger dev_projects_set_sales_id
    before insert on public.dev_projects
    for each row execute function public.set_sales_id_default();

create trigger dev_projects_check_options
    before insert or update on public.dev_projects
    for each row execute function public.ddc_check_option_category('responsible_department_id', 'department');

create table public.dev_project_requirements (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.dev_projects(id) on delete cascade,
    category text not null default 'technical'
        check (category in ('technical', 'material', 'process', 'tooling', 'quality', 'packaging', 'commercial', 'other')),
    requirement text not null,
    source text,
    status text not null default 'open' check (status in ('open', 'clarifying', 'agreed', 'rejected')),
    sort_order integer not null default 0
);

create index dev_project_requirements_project_idx on public.dev_project_requirements using btree (project_id);

create table public.dev_project_milestones (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.dev_projects(id) on delete cascade,
    name text not null,
    department_id bigint references public.master_options(id),
    sales_id bigint references public.sales(id),
    planned_date date,
    actual_date date,
    status text not null default 'planned' check (status in ('planned', 'in_progress', 'done', 'delayed', 'cancelled')),
    notes text,
    sort_order integer not null default 0
);

create index dev_project_milestones_project_idx on public.dev_project_milestones using btree (project_id, sort_order);

create trigger dev_project_milestones_check_options
    before insert or update on public.dev_project_milestones
    for each row execute function public.ddc_check_option_category('department_id', 'department');

create table public.dev_project_samples (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.dev_projects(id) on delete cascade,
    sample_no text not null,
    sample_type text not null default 'sample' check (sample_type in ('prototype', 'sample', 'pilot_lot')),
    quantity numeric(18, 3) check (quantity is null or quantity > 0),
    requested_date date,
    planned_submission_date date,
    submitted_date date,
    status text not null default 'requested'
        check (status in ('requested', 'in_preparation', 'submitted', 'feedback_received', 'closed', 'cancelled')),
    customer_feedback text,
    result text check (result in ('approved', 'conditionally_approved', 'rejected')),
    report_ref text,
    constraint dev_project_samples_unique unique (project_id, sample_no)
);

create table public.dev_project_risks (
    id bigint generated by default as identity primary key,
    project_id bigint not null references public.dev_projects(id) on delete cascade,
    description text not null,
    severity text not null default 'medium' check (severity in ('low', 'medium', 'high')),
    mitigation text,
    status text not null default 'open' check (status in ('open', 'mitigating', 'closed', 'accepted')),
    sales_id bigint references public.sales(id)
);

create index dev_project_risks_project_idx on public.dev_project_risks using btree (project_id);

--
-- OBM / aftermarket: dealer and distributor network of company owned brands
--

create table public.dealer_networks (
    id bigint generated by default as identity primary key,
    brand_id bigint not null references public.brands(id) on delete restrict,
    company_id bigint not null references public.companies(id) on delete cascade,
    supplied_by_company_id bigint references public.companies(id) on delete set null,
    network_role text not null default 'dealer' check (network_role in ('distributor', 'dealer', 'wholesaler', 'retailer')),
    territory_id bigint references public.territories(id) on delete set null,
    status text not null default 'prospect' check (status in ('prospect', 'active', 'suspended', 'terminated')),
    start_date date,
    end_date date,
    notes text,
    sales_id bigint references public.sales(id),
    created_at timestamp with time zone not null default now(),
    constraint dealer_networks_unique unique nulls not distinct (brand_id, company_id, territory_id),
    constraint dealer_networks_not_self_supplied check (supplied_by_company_id is null or supplied_by_company_id <> company_id),
    constraint dealer_networks_dates_ordered check (end_date is null or start_date is null or end_date >= start_date)
);

create index dealer_networks_company_idx on public.dealer_networks using btree (company_id);
create index dealer_networks_territory_idx on public.dealer_networks using btree (territory_id);

create trigger dealer_networks_set_sales_id
    before insert on public.dealer_networks
    for each row execute function public.set_sales_id_default();

create table public.dealer_product_coverage (
    id bigint generated by default as identity primary key,
    dealer_network_id bigint not null references public.dealer_networks(id) on delete cascade,
    node_id bigint references public.product_hierarchy_nodes(id) on delete cascade,
    product_id bigint references public.products(id) on delete cascade,
    notes text,
    constraint dealer_product_coverage_has_target check (num_nonnulls(node_id, product_id) = 1),
    constraint dealer_product_coverage_unique unique nulls not distinct (dealer_network_id, node_id, product_id)
);

--
-- Customer complaints and service cases
