--
-- DDC CRM - 6/8 - ERP integration layer (Microsoft Dynamics 365 Finance and Operations)
--
-- The CRM is independent from the ERP. This schema holds connector configuration,
-- cross-system identifier mappings, synchronization bookkeeping and read-only
-- copies of ERP owned documents. Real ERP connectivity is DISABLED by default and
-- needs both an explicit approval record and server side credentials.
-- No credential, token or connection string is ever stored in these tables.
--

create table public.erp_connector_config (
    id integer primary key default 1,
    connector_type text not null default 'mock' check (connector_type in ('mock', 'd365fo')),
    environment_type text not null default 'none' check (environment_type in ('none', 'mock', 'sandbox', 'production')),
    -- Host only (no secret). Informational until integration is approved.
    environment_url text,
    is_enabled boolean not null default false,
    approval_status text not null default 'not_requested'
        check (approval_status in ('not_requested', 'pending', 'approved', 'rejected')),
    approved_by_name text,
    approved_at timestamp with time zone,
    approval_reference text,
    notes text,
    updated_at timestamp with time zone not null default now(),
    constraint erp_connector_config_singleton check (id = 1),
    -- A real connector can only be enabled once approval has been recorded
    constraint erp_connector_config_real_needs_approval check (
        connector_type = 'mock' or not is_enabled or approval_status = 'approved'
    ),
    constraint erp_connector_config_mock_env check (
        connector_type <> 'mock' or environment_type in ('none', 'mock')
    )
);

-- Dynamics 365 F&O legal entities (dataAreaId). ERP keys are only unique within one legal entity.
create table public.erp_legal_entities (
    id bigint generated by default as identity primary key,
    data_area_id text not null unique check (data_area_id = lower(data_area_id) and length(data_area_id) between 1 and 4),
    name text not null,
    is_active boolean not null default true,
    is_default boolean not null default false,
    is_verified boolean not null default false,
    notes text
);

create unique index erp_legal_entities_single_default_idx on public.erp_legal_entities using btree (is_default) where is_default;

-- One row per integration contract. Direction, system of record and permitted
-- operations are decisions owned by DDC stakeholders: they start as 'proposed'.
create table public.erp_entity_configs (
    entity text primary key check (entity ~ '^[a-z][a-z_]*$'),
    label text not null,
    erp_entity_name text not null,
    crm_table text not null,
    direction text not null default 'disabled' check (direction in ('disabled', 'inbound', 'outbound', 'bidirectional')),
    system_of_record text not null default 'undecided' check (system_of_record in ('undecided', 'erp', 'crm')),
    allowed_operations text[] not null default '{read}'::text[]
        check (allowed_operations <@ array['read', 'create', 'update', 'delete']::text[]),
    decision_status text not null default 'proposed' check (decision_status in ('proposed', 'confirmed')),
    decision_note text,
    is_enabled boolean not null default false,
    page_size integer not null default 100 check (page_size between 1 and 10000),
    sort_order integer not null default 0,
    last_synced_at timestamp with time zone
);

create table public.erp_field_mappings (
    id bigint generated by default as identity primary key,
    entity text not null references public.erp_entity_configs(entity) on update cascade on delete cascade,
    crm_field text not null,
    erp_field text not null,
    transform text not null default 'none' check (transform in ('none', 'trim', 'upper', 'lower', 'number', 'date', 'boolean')),
    is_key boolean not null default false,
    is_active boolean not null default true,
    is_verified boolean not null default false,
    notes text,
    constraint erp_field_mappings_unique unique (entity, crm_field)
);

-- Persistent CRM <-> ERP identifier mapping, scoped by legal entity.
create table public.erp_external_ids (
    id bigint generated by default as identity primary key,
    entity text not null references public.erp_entity_configs(entity) on update cascade,
    data_area_id text not null references public.erp_legal_entities(data_area_id) on update cascade,
    erp_key text not null,
    crm_table text not null,
    crm_id bigint not null,
    payload_hash text,
    erp_modified_at timestamp with time zone,
    last_synced_at timestamp with time zone not null default now(),
    constraint erp_external_ids_erp_unique unique (entity, data_area_id, erp_key),
    constraint erp_external_ids_crm_unique unique (entity, data_area_id, crm_table, crm_id)
);

create index erp_external_ids_crm_idx on public.erp_external_ids using btree (crm_table, crm_id);

-- Incremental synchronization position, per entity AND legal entity
create table public.erp_sync_cursors (
    id bigint generated by default as identity primary key,
    entity text not null references public.erp_entity_configs(entity) on update cascade on delete cascade,
    data_area_id text not null references public.erp_legal_entities(data_area_id) on update cascade on delete cascade,
    cursor_value text,
    last_synced_at timestamp with time zone,
    constraint erp_sync_cursors_unique unique (entity, data_area_id)
);

create table public.erp_sync_runs (
    id bigint generated by default as identity primary key,
    entity text not null references public.erp_entity_configs(entity) on update cascade,
    data_area_id text not null,
    connector_type text not null,
    direction text not null,
    mode text not null default 'incremental' check (mode in ('incremental', 'full', 'retry', 'reconcile')),
    status text not null default 'running' check (status in ('running', 'succeeded', 'partial', 'failed')),
    started_at timestamp with time zone not null default now(),
    finished_at timestamp with time zone,
    cursor_before text,
    cursor_after text,
    pages_read integer not null default 0,
    records_read integer not null default 0,
    records_created integer not null default 0,
    records_updated integer not null default 0,
    records_unchanged integer not null default 0,
    records_conflicted integer not null default 0,
    records_failed integer not null default 0,
    throttle_waits integer not null default 0,
    triggered_by bigint references public.sales(id),
    error_message text
);

create index erp_sync_runs_entity_idx on public.erp_sync_runs using btree (entity, started_at desc);

create table public.erp_sync_errors (
    id bigint generated by default as identity primary key,
    run_id bigint references public.erp_sync_runs(id) on delete cascade,
    entity text not null,
    data_area_id text not null,
    erp_key text,
    error_type text not null default 'error' check (error_type in ('error', 'conflict', 'validation', 'mapping')),
    error_message text not null,
    payload jsonb,
    attempts integer not null default 1,
    next_retry_at timestamp with time zone,
    is_resolved boolean not null default false,
    resolved_at timestamp with time zone,
    created_at timestamp with time zone not null default now()
);

create index erp_sync_errors_open_idx on public.erp_sync_errors using btree (entity, is_resolved, next_retry_at);

--
-- Read-only copies of ERP owned documents. They feed the "confirmed orders" and
-- "invoiced revenue" figures. They stay empty until a synchronization runs:
-- the CRM never invents these numbers.
--

create table public.erp_sales_orders (
    id bigint generated by default as identity primary key,
    data_area_id text not null,
    sales_order_number text not null,
    company_id bigint references public.companies(id) on delete set null,
    erp_customer_account text,
    order_date date,
    requested_ship_date date,
    status text,
    currency text,
    total_amount numeric(18, 4),
    quotation_id bigint references public.quotations(id) on delete set null,
    source text not null default 'erp',
    synced_at timestamp with time zone not null default now(),
    constraint erp_sales_orders_unique unique (data_area_id, sales_order_number)
);

create index erp_sales_orders_company_idx on public.erp_sales_orders using btree (company_id, order_date);

create table public.erp_sales_order_lines (
    id bigint generated by default as identity primary key,
    data_area_id text not null,
    sales_order_number text not null,
    line_number numeric(18, 4) not null,
    sales_order_id bigint references public.erp_sales_orders(id) on delete cascade,
    product_id bigint references public.products(id) on delete set null,
    erp_item_number text,
    quantity numeric(18, 4),
    uom text,
    unit_price numeric(18, 4),
    line_amount numeric(18, 4),
    synced_at timestamp with time zone not null default now(),
    constraint erp_sales_order_lines_unique unique (data_area_id, sales_order_number, line_number)
);

create index erp_sales_order_lines_order_idx on public.erp_sales_order_lines using btree (sales_order_id);
create index erp_sales_order_lines_product_idx on public.erp_sales_order_lines using btree (product_id);

create table public.erp_deliveries (
    id bigint generated by default as identity primary key,
    data_area_id text not null,
    delivery_number text not null,
    sales_order_number text,
    company_id bigint references public.companies(id) on delete set null,
    delivery_date date,
    status text,
    synced_at timestamp with time zone not null default now(),
    constraint erp_deliveries_unique unique (data_area_id, delivery_number)
);

create table public.erp_invoices (
    id bigint generated by default as identity primary key,
    data_area_id text not null,
    invoice_number text not null,
    sales_order_number text,
    company_id bigint references public.companies(id) on delete set null,
    erp_customer_account text,
    invoice_date date,
    due_date date,
    currency text,
    invoice_amount numeric(18, 4),
    paid_amount numeric(18, 4),
    synced_at timestamp with time zone not null default now(),
    constraint erp_invoices_unique unique (data_area_id, invoice_number)
);

create index erp_invoices_company_idx on public.erp_invoices using btree (company_id, invoice_date);

create table public.erp_inventory_availability (
    id bigint generated by default as identity primary key,
    data_area_id text not null,
    erp_item_number text not null,
    site_id text not null default '',
    warehouse_id text not null default '',
    product_id bigint references public.products(id) on delete set null,
    available_quantity numeric(18, 4),
    on_hand_quantity numeric(18, 4),
    uom text,
    as_of timestamp with time zone,
    synced_at timestamp with time zone not null default now(),
    constraint erp_inventory_availability_unique unique (data_area_id, erp_item_number, site_id, warehouse_id)
);

create index erp_inventory_availability_product_idx on public.erp_inventory_availability using btree (product_id);

create table public.erp_price_list_entries (
    id bigint generated by default as identity primary key,
    data_area_id text not null,
    price_key text not null,
    erp_item_number text,
    product_id bigint references public.products(id) on delete set null,
    price_group text,
    erp_customer_account text,
    currency text,
    unit_price numeric(18, 4),
    quantity_from numeric(18, 4),
    valid_from date,
    valid_to date,
    synced_at timestamp with time zone not null default now(),
    constraint erp_price_list_entries_unique unique (data_area_id, price_key)
);

create index erp_price_list_entries_product_idx on public.erp_price_list_entries using btree (product_id);
