create or replace function public.ddc_assign_customer_code() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
    if new.customer_code is null or btrim(new.customer_code) = '' then
        new.customer_code := 'CUS-' || lpad(nextval('public.customer_code_seq')::text, 6, '0');
    end if;
    return new;
end;
$$;

