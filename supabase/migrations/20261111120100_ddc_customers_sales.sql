create or replace function public.ddc_action_item_completed() returns trigger
    language plpgsql
    set search_path to ''
    as $$
begin
    if new.status = 'done' and new.completed_at is null then
        new.completed_at := now();
    elsif new.status <> 'done' then
        new.completed_at := null;
    end if;
    return new;
end;
$$;

