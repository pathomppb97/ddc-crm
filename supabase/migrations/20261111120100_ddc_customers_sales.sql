drop view public.companies_summary;

create view public.companies_summary with (security_invoker = on) as
select
    c.id,
    c.created_at,
    c.name,
    c.sector,
    c.size,
    c.linkedin_url,
    c.website,
    c.phone_number,
    c.address,
    c.zipcode,
    c.city,
    c.state_abbr,
    c.sales_id,
    c.context_links,
    c.country,
    c.description,
    c.revenue,
    c.tax_identifier,
    c.logo,
    c.customer_code,
    c.legal_name,
    c.parent_company_id,
    c.org_type,
    c.branch_code,
    c.lifecycle_status_id,
    c.category_id,
    c.territory_id,
    c.province,
    c.email,
    c.custom_fields,
    c.updated_at,
    count(distinct d.id) as nb_deals,
    count(distinct co.id) as nb_contacts,
    (select coalesce(array_agg(distinct cbm.business_model_id), '{}'::bigint[])
        from public.company_business_models cbm where cbm.company_id = c.id) as business_model_ids,
    (select coalesce(array_agg(distinct cbm.division_id) filter (where cbm.division_id is not null), '{}'::bigint[])
        from public.company_business_models cbm where cbm.company_id = c.id) as division_ids,
    (select max(a.start_at) from public.activities a
        where a.company_id = c.id and a.status = 'completed') as last_activity_at
from public.companies c
    left join public.deals d on c.id = d.company_id
    left join public.contacts co on c.id = co.company_id
group by c.id;

