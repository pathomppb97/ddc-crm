-- Workbook evidence is separate from executable RFQs, products and ERP orders.
create table public.customer_source_rows (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    source_file text not null,
    sheet_name text not null,
    source_row integer not null check (source_row > 0),
    region text,
    source_sequence integer,
    raw_cells jsonb not null,
    review_notes text,
    unique (source_file, sheet_name, source_row),
    unique (id, company_id)
);

create table public.customer_fleets (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    source_id bigint not null,
    brands_raw text,
    quantities_raw text,
    capacity_kton_raw text,
    foreign key (source_id, company_id) references public.customer_source_rows(id, company_id)
);

create table public.customer_requirements (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    source_id bigint not null,
    product_family text not null check (product_family in ('Basecutter Blade', 'Chopper Blade')),
    old_brands_raw text,
    specification_raw text,
    target_cost_raw text,
    seasonal_usage_raw text,
    blades_per_machine_raw text,
    foreign key (source_id, company_id) references public.customer_source_rows(id, company_id),
    unique (source_id, product_family),
    unique (id, company_id)
);

create table public.customer_samples (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    source_id bigint not null,
    requirement_id bigint not null,
    product_family text not null,
    specification_raw text,
    quantity_raw text,
    sample_date_raw text,
    testing_date_raw text,
    customer_pic_raw text,
    foreign key (source_id, company_id) references public.customer_source_rows(id, company_id),
    foreign key (requirement_id, company_id) references public.customer_requirements(id, company_id)
);

create table public.customer_purchase_history (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    source_id bigint not null,
    requirement_id bigint not null,
    season text not null check (season in ('25-26', '26-27')),
    specification_raw text,
    quantity_raw text,
    sent_date_raw text,
    review_notes text,
    foreign key (source_id, company_id) references public.customer_source_rows(id, company_id),
    foreign key (requirement_id, company_id) references public.customer_requirements(id, company_id),
    unique (source_id, season)
);

-- Authenticated clients can read evidence only through an accessible customer.
-- Import writes are reserved for the backend service or database administrator.
do $$
declare t text;
begin
    foreach t in array array['customer_source_rows', 'customer_fleets', 'customer_requirements', 'customer_samples', 'customer_purchase_history'] loop
        execute format('create index %I on public.%I (company_id)', t || '_company_idx', t);
        execute format('alter table public.%I enable row level security', t);
        execute format('create policy ddc_select on public.%I for select to authenticated using (public.ddc_can_any_scope(''customers'', ''read'') and exists (select 1 from public.companies c where c.id = %I.company_id))', t, t);
        execute format('grant select on public.%I to authenticated', t);
        execute format('grant all on public.%I to service_role', t);
        insert into public.table_permission_map (table_name, resource, parent_table, parent_fk, parent_owner_column)
        values (t, 'customers', 'companies', 'company_id', 'sales_id');
    end loop;
end $$;
