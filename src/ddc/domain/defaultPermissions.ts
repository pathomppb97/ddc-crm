/** Expands the grants with the same "last grant wins" rule as the SQL seed (on conflict do update). */
export const defaultPermissionsFor = (
  roleKey: string | null | undefined,
): Permission[] => {
  const byKey = new Map<string, Permission>();
  for (const [resources, actions, scope = "all"] of GRANTS[roleKey ?? ""] ??
    []) {
    for (const resource of resources) {
      for (const action of actions) {
        byKey.set(`${resource}:${action}`, { resource, action, scope });
      }
    }
  }
  return [...byKey.values()];
};

